#pragma once
#include <stdint.h>

// =====================================================================
// 链路质量统计（重发率推算信号质量）
// ---------------------------------------------------------------------
// 背景：BLE 连接建立后，上位机无法从链路层直接读取信号强度（BlueZ/tinygo
// 均不暴露 LL 统计）。本模块在固件侧统计"接收侧异常帧率"作为重发率近似：
//   - 解密失败（AES-GCM auth 失败 → 帧在链路上损坏/被干扰）
//   - CRC 校验失败（帧损坏）
//   - SeqID 重复（上位机重发同一条指令 = 链路上一次 ACK 丢失/重传迹象）
//   - SeqID 跳变（丢帧）
// 信号质量 = 100 - 窗口内异常帧率 × 100（0~100，越大越好）。
// 上位机通过 PING 应答获取该值，替代无法实时读取的 RSSI。
// =====================================================================

// 初始化/重置统计（连接建立时调用，重置 SeqID 基线避免误判）
void lqInit();

// 记录一帧的接收结果：
//   ok = true ：帧解析成功（内部按 seq 检查重复/跳变）
//   ok = false：解密失败或 CRC 失败（seq 参数忽略，记一帧异常）
void lqNoteFrame(uint8_t seq, bool ok);

// 当前推算信号质量（0~100，窗口未满时按已收帧数计算）
uint8_t lqGetQuality();
